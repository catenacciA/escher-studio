std::vector<Orbit> orbits(const Group &g, Vec site) {
    std::vector<Orbit> result;
    for (size_t k = 0; k < g.ops.size(); ++k) {
        Vec p = g.ops[k](site);
        for (size_t j = 0; j <= k; ++j) {
            Vec d = p - g.ops[j](site);
            if (length(wrapCentered(d)) < 1e-9) {
                result.push_back({int(j), int(std::lround(d.x)), int(std::lround(d.y))});
                break;
            }
        }
    }
    return result;
}

