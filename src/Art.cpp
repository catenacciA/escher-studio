struct Random {
    uint64_t state;

    uint64_t next() {
        uint64_t z = (state += 0x9e3779b97f4a7c15ull);
        z = (z ^ (z >> 30)) * 0xbf58476d1ce4e5b9ull;
        z = (z ^ (z >> 27)) * 0x94d049bb133111ebull;
        return z ^ (z >> 31);
    }

    double uniform(double a = 0, double b = 1) {
        return a + (b - a) * double(next() >> 11) * 0x1p-53;
    }
};

Rgb hex(uint32_t v) {
    return {float((v >> 16) & 255) / 255, float((v >> 8) & 255) / 255, float(v & 255) / 255};
}

int parity(int n) {
    return ((n % 2) + 2) % 2;
}

struct Tile {
    int site = 0, op = 0, nx = 0, ny = 0;
    Vec centre; // lattice coordinates
    double distance = std::numeric_limits<double>::infinity();
};

struct Layout {
    const Group &group;
    Mat m;
    std::vector<Vec> sites;
    std::vector<std::vector<Orbit>> orbit;

    // Canonical key of a tile: site, canonical op, parity of its translation.
    int key(const Tile &t) const {
        const Orbit &o = orbit[t.site][t.op];
        return (t.site * maxOps + o.op) * 4 + parity(t.nx + o.mx) + 2 * parity(t.ny + o.my);
    }

    // The nearest tile and the nearest different tile, in the world metric.
    std::pair<Tile, Tile> nearest(Vec s) const {
        Tile first, second;
        auto visit = [&](auto &&use) {
            for (size_t i = 0; i < sites.size(); ++i)
                for (size_t k = 0; k < group.ops.size(); ++k) {
                    Vec p = group.ops[k](sites[i]);
                    int bx = int(std::lround(s.x - p.x)), by = int(std::lround(s.y - p.y));
                    for (int dy = -1; dy <= 1; ++dy)
                        for (int dx = -1; dx <= 1; ++dx) {
                            Tile t{int(i),
                                   int(k),
                                   bx + dx,
                                   by + dy,
                                   p + Vec{double(bx + dx), double(by + dy)},
                                   0};
                            t.distance = length(m * (s - t.centre));
                            use(t);
                        }
                }
        };
        visit([&](const Tile &t) {
            if (t.distance < first.distance)
                first = t;
        });
        visit([&](const Tile &t) {
            if (t.distance < second.distance && length(t.centre - first.centre) > 1e-9)
                second = t;
        });
        return {first, second};
    }
};

int stabilizer(const Group &g, Vec p) {
    int n = 0;
    for (const Op &op : g.ops)
        n += length(wrapCentered(op(p) - p)) < 1e-9;
    return n;
}

bool equivalent(const Group &g, Vec a, Vec b) {
    for (const Op &op : g.ops)
        if (length(wrapCentered(op(a) - b)) < 1e-9)
            return true;
    return false;
}

double inradius(const Layout &layout, Vec site) {
    double best = std::numeric_limits<double>::infinity();
    for (Vec other : layout.sites)
        for (const Op &op : layout.group.ops) {
            Vec p = op(other);
            for (int dy = -2; dy <= 2; ++dy)
                for (int dx = -2; dx <= 2; ++dx) {
                    double d = length(layout.m * (p + Vec{double(dx), double(dy)} - site));
                    if (d > 1e-9)
                        best = std::min(best, d);
                }
        }
    return best / 2;
}

bool colour(const std::vector<std::vector<int>> &edges, int colours, std::vector<int> &result) {
    const int n = int(edges.size());
    std::vector<int> order(n);
    for (int i = 0; i < n; ++i)
        order[i] = i;
    std::stable_sort(order.begin(), order.end(),
                     [&](int a, int b) { return edges[a].size() > edges[b].size(); });
    result.assign(n, 0);
    std::vector<int> assigned(n, -1);
    int steps = 0;
    auto place = [&](auto &&self, int at) -> bool {
        if (at == n)
            return true;
        if (++steps > 200000)
            return false;
        int v = order[at];
        for (int c = 0; c < colours; ++c) {
            bool free = true;
            for (int w : edges[v])
                if (assigned[w] == c) {
                    free = false;
                    break;
                }
            if (!free)
                continue;
            assigned[v] = c;
            if (self(self, at + 1))
                return true;
        }
        assigned[v] = -1;
        return false;
    };
    if (!place(place, 0))
        return false;
    for (int i = 0; i < n; ++i)
        result[i] = std::max(assigned[i], 0);
    return true;
}

// Groups generated by reflections: Dirichlet tiles of one orbit are bounded by mirrors alone,
// which no symmetric deformation can bend. Their tiles sit on mirror intersections instead.
bool kaleidoscopic(const Group &g) {
    for (const char *name : {"pmm", "p4m", "p3m1", "p6m"})
        if (!std::strcmp(g.name, name))
            return true;
    return false;
}
