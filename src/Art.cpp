Art makeArt(const State &state) {
    const Group &g = groups()[std::clamp(state.group, 0, int(groups().size()) - 1)];
    Layout layout{g, latticeBasis(g.lattice), {}, {}};
    Random random{0x5eed0000ull + state.seed * 0x10001ull + uint64_t(state.group) * 977};
    if (kaleidoscopic(g)) {
        // Two inequivalent mirror intersections; every lattice point of the group's special
        // positions lies on the 1/6 grid.
        std::vector<Vec> special;
        for (int y = 0; y < 6; ++y)
            for (int x = 0; x < 6; ++x) {
                Vec p{x / 6.0, y / 6.0};
                if (stabilizer(g, p) < 4)
                    continue;
                bool fresh = true;
                for (Vec q : special)
                    fresh = fresh && !equivalent(g, p, q);
                if (fresh)
                    special.push_back(p);
            }
        size_t a = size_t(random.uniform(0, double(special.size())));
        size_t b = (a + 1 + size_t(random.uniform(0, double(special.size() - 1)))) % special.size();
        layout.sites = {special[a], special[b]};
    } else {
        // One generic site among the roomier candidates: varied but well-proportioned tiles.
        std::vector<std::pair<double, Vec>> candidates;
        for (int i = 0; i < 96; ++i) {
            Vec p{random.uniform(), random.uniform()};
            Layout probe{g, layout.m, {p}, {}};
            candidates.push_back({inradius(probe, p), p});
        }
        std::sort(candidates.begin(), candidates.end(),
                  [](const auto &x, const auto &y) { return x.first > y.first; });
        layout.sites = {candidates[size_t(random.uniform(0, 24))].second};
    }
    Art art;
    art.inradius = std::numeric_limits<double>::infinity();
    for (Vec p : layout.sites) {
        layout.orbit.push_back(orbits(g, p));
        Site site;
        site.position = p;
        site.symmetric = stabilizer(g, p) > 1;
        site.inradius = inradius(layout, p);
        double angle = random.uniform(0, 2 * M_PI);
        if (!site.symmetric)
            site.eye = Vec{std::cos(angle), std::sin(angle)} * (site.inradius * .46);
        art.sites.push_back(site);
        art.inradius = std::min(art.inradius, site.inradius);
    }

    // Tile adjacency on the 2 × 2 supercell, sampled at sub-tile resolution.
    const int count = maxSites * maxOps * 4, samples = 360;
    std::vector<std::vector<int>> adjacent(count);
    const double spacing = 2.0 / samples * 1.5;
    for (int y = 0; y < samples; ++y)
        for (int x = 0; x < samples; ++x) {
            Vec s{(x + .5) * 2 / samples, (y + .5) * 2 / samples};
            auto [a, b] = layout.nearest(s);
            double gap = (b.distance * b.distance - a.distance * a.distance) /
                         (2 * length(layout.m * (b.centre - a.centre)));
            if (gap > spacing)
                continue;
            int i = layout.key(a), j = layout.key(b);
            if (i != j &&
                std::find(adjacent[i].begin(), adjacent[i].end(), j) == adjacent[i].end()) {
                adjacent[i].push_back(j);
                adjacent[j].push_back(i);
            }
        }
    // Prefer few colours, then colourings that ignore the supercell (period 1, then checker).
    for (int colours = 2; colours <= 6; ++colours)
        for (int mode = 0; mode < 3; ++mode) {
            auto reduce = [&](int node) {
                int p = node % 4, base = node / 4 * 4;
                return mode == 0 ? base : mode == 1 ? base + ((p & 1) ^ (p >> 1)) : node;
            };
            std::vector<std::vector<int>> edges(count);
            bool loop = false;
            for (int i = 0; i < count; ++i)
                for (int j : adjacent[i]) {
                    int a = reduce(i), b = reduce(j);
                    if (a == b)
                        loop = true;
                    else if (std::find(edges[a].begin(), edges[a].end(), b) == edges[a].end())
                        edges[a].push_back(b);
                }
            std::vector<int> result;
            if (loop || !colour(edges, colours, result))
                continue;
            art.color.resize(count);
            for (int i = 0; i < count; ++i)
                art.color[i] = result[reduce(i)];
            art.colors = colours;
            return art;
        }
    art.color.assign(count, 0);
    art.colors = 1;
    return art;
}

State sculpt(const State &state, uint32_t seed) {
    const Group &g = groups()[state.group];
    const Mat m = cellBasis(state), mi = inverse(m);
    Random random{0xc0ffeeull + seed * 0x9e37ull};
    if (state.artwork >= 0) {
        // Artwork has no known tile edges: broad pushes at random points, scaled to the motif.
        State out = state;
        out.handles.clear();
        const double motif = std::sqrt(std::abs(m.a * m.d - m.b * m.c) / g.ops.size());
        out.sigma = std::clamp(random.uniform(2.2, 3.4) / motif, 1.5, 14.0);
        const int wanted = 4 + int(random.uniform(0, 3));
        for (int attempt = 0; attempt < 400 && int(out.handles.size()) < wanted; ++attempt) {
            Vec s{random.uniform(), random.uniform()};
            if (!canAdd(out, s))
                continue;
            double angle = random.uniform(0, 2 * M_PI), push = motif * random.uniform(.07, .14);
            out.handles.push_back({s, s + mi * (Vec{std::cos(angle), std::sin(angle)} * push)});
        }
        return out;
    }
    Art art = makeArt(state);
    Layout layout{g, m, {}, {}};
    for (const Site &site : art.sites) {
        layout.sites.push_back(site.position);
        layout.orbit.push_back(orbits(g, site.position));
    }
    State out = state;
    out.handles.clear();
    out.sigma = std::clamp(random.uniform(.45, .8) / art.inradius, 1.5, 12.0);
    const int wanted = 5 + int(random.uniform(0, 3));
    for (int attempt = 0; attempt < 400 && int(out.handles.size()) < wanted; ++attempt) {
        Vec s{random.uniform(), random.uniform()};
        auto [a, b] = layout.nearest(s);
        Vec across = m * (b.centre - a.centre);
        double span = length(across);
        Vec normal = across * (1 / span);
        double gap = (b.distance * b.distance - a.distance * a.distance) / (2 * span);
        Vec edge = wrap(mi * (m * s + normal * gap));
        if (!canAdd(out, edge))
            continue;
        Vec tangent{-normal.y, normal.x};
        double push = art.inradius * random.uniform(.55, 1.0) * (random.uniform() < .5 ? -1 : 1);
        double slide = art.inradius * random.uniform(-.35, .35);
        out.handles.push_back({edge, edge + mi * (normal * push + tangent * slide)});
    }
    return out;
}
